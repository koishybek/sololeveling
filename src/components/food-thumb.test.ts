import { describe, expect, it } from "vitest";
import { foodEmoji } from "./food-thumb";

describe("foodEmoji", () => {
  it.each([
    ["Кофе с молоком", "☕"],
    ["Высокобелковый батончик", "🍫"],
    ["Высокобелковое печенье", "🍪"],
    ["Гречка", "🥣"],
    ["Форель на гриле", "🐟"],
    ["Яичница из 2 яиц", "🍳"],
    ["Плов с бараниной", "🍛"],
    ["Манты", "🥟"],
    ["Eggplant", "🍆"],
    ["Греческий йогурт", "🥛"],
    ["Банан", "🍌"],
    ["Говяжий стейк", "🥩"],
    ["Арахисовая паста", "🥜"],
  ])("%s → %s", (name, emoji) => {
    expect(foodEmoji(name)).toBe(emoji);
  });
});
